/**
 * Builds src/i18n/messages.js from src/i18n/locales/{it,en,es,de,fr,nl}.json.
 *
 *     node tools/i18n-build.mjs           write messages.js
 *     node tools/i18n-build.mjs --check   fail if messages.js is out of date (CI, tests)
 *
 * The JSON files are the source of truth: edit them, then run this script.
 * messages.js exists because content scripts are classic scripts and cannot
 * import JSON.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LANGS = ['it', 'en', 'es', 'de', 'fr', 'nl', 'pl', 'pt', 'sv', 'ro', 'cs', 'da', 'fi', 'no', 'sk', 'hu', 'el', 'hr', 'sl', 'bg', 'lt', 'lv', 'et'];
const OUT = join(ROOT, 'src/i18n/messages.js');
const BOOT_OUT = join(ROOT, 'src/i18n/messages-boot.js');

/**
 * The texts a content script may need when it cannot ask the service worker for
 * the rest: the "extension unreachable" errors and the card that says the check
 * failed. Everything else is fetched for the one language in use, when a
 * warning is about to be shown (see bridge.js): loading every text in every
 * language into every page and frame cost over a megabyte each time.
 */
export const BOOT_IDS = [
  'extensionUnreachableReloadPage', 'noReplyFromAnalysisEngine', 'unknownError', 'errorDuringAnalysis',
  'analysisFailed', 'iCouldnTCheckCommitment', 'canGoAheadAnywayButWithout', 'goBack', 'continueAnyway',
  'canContinueNow', 'upgradePro50AnalysesMonth',
];

const readAll = () => Object.fromEntries(LANGS.map((l) => [l, JSON.parse(readFileSync(join(ROOT, `src/i18n/locales/${l}.json`), 'utf8'))]));

export function buildMessages() {
  return `/* Generated by tools/i18n-build.mjs from src/i18n/locales/*.json: do not edit by hand. */
globalThis.AF_I18N.add(${JSON.stringify(readAll(), null, 1)});
`;
}

/** The few texts content scripts carry with them (BOOT_IDS), in every language. */
export function buildBootMessages() {
  const all = readAll();
  const m = Object.fromEntries(LANGS.map((l) => [l, Object.fromEntries(BOOT_IDS.map((id) => {
    if (typeof all[l][id] !== 'string') throw new Error(`boot text "${id}" is missing in ${l}`);
    return [id, all[l][id]];
  }))]));
  return `/* Generated by tools/i18n-build.mjs from src/i18n/locales/*.json: do not edit by hand. */
globalThis.AF_I18N.add(${JSON.stringify(m)});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = [[OUT, buildMessages(), 'messages.js'], [BOOT_OUT, buildBootMessages(), 'messages-boot.js']];
  if (process.argv.includes('--check')) {
    for (const [path, out, name] of files) {
      let cur = '';
      try { cur = readFileSync(path, 'utf8'); } catch { /* missing */ }
      if (cur !== out) { console.error(`src/i18n/${name} is out of date: run node tools/i18n-build.mjs`); process.exit(1); }
    }
    console.log('messages.js and messages-boot.js are up to date');
  } else {
    for (const [path, out] of files) writeFileSync(path, out);
    console.log(`messages.js written (${Object.keys(JSON.parse(readFileSync(join(ROOT, 'src/i18n/locales/it.json'), 'utf8'))).length} ids), messages-boot.js (${BOOT_IDS.length} ids)`);
  }
}
