/**
 * Builds src/i18n/messages.js from src/i18n/locales/{it,en,es,de,fr,nl}.json.
 *
 *     node tools/i18n-build.mjs           write messages.js
 *     node tools/i18n-build.mjs --check   fail if messages.js is out of date (CI, tests)
 *
 * The JSON files are the source of truth: edit them, then run this script.
 * messages.js exists because content scripts are classic scripts and cannot
 * import JSON.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LANGS = ['it', 'en', 'es', 'de', 'fr', 'nl', 'pl', 'pt'];
const OUT = join(ROOT, 'src/i18n/messages.js');

export function buildMessages() {
  const m = Object.fromEntries(LANGS.map((l) => [l, JSON.parse(readFileSync(join(ROOT, `src/i18n/locales/${l}.json`), 'utf8'))]));
  return `/* Generated by tools/i18n-build.mjs from src/i18n/locales/*.json: do not edit by hand. */
globalThis.AF_I18N.add(${JSON.stringify(m, null, 1)});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = buildMessages();
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (cur !== out) { console.error('src/i18n/messages.js is out of date: run node tools/i18n-build.mjs'); process.exit(1); }
    console.log('messages.js is up to date');
  } else {
    writeFileSync(OUT, out);
    console.log(`messages.js written (${Object.keys(JSON.parse(readFileSync(join(ROOT, 'src/i18n/locales/it.json'), 'utf8'))).length} ids)`);
  }
}
